"""Ремонт текстового слоя сканированных PDF/DjVu.

Учебники, которые студенты приносят в Vedomo, — это чаще всего сканы,
прогнанные чужим OCR десять-двадцать лет назад. Текстовый слой в них уже
испорчен, и никакая замена библиотеки-экстрактора этого не исправит: мы читаем
ровно то, что записал в файл FineReader.

Две поломки встречаются в таких файлах систематически.

**Перенос слова.** Экстрактор отдаёт вёрстку страницы, поэтому слово, разорванное
переносом, приходит как ``веществен<U+00AD>\\nными``. В индекс попадают два
обрубка вместо одного слова, и поиск по «вещественными» их не находит.

**Подмена букв-гомоглифов.** OCR путает кириллицу с визуально похожей латиницей:
на 245 КБ учебника Краснова (замерено 01.09.2026) — 411 раз ``n`` вместо ``п``
(«nри», «nолучим»), 109 раз ``r`` вместо ``г`` («rде», «этоrо»). Для читателя это
почти незаметно, а для эмбеддингов «nри» и «при» — разные токены, так что
retrieval по таким словам просто не работает.

Чего этот модуль сознательно **не** делает: не угадывает искорёженные формулы
(``1/(t)/`` вместо ``|f(t)|``, ``j(t)`` вместо ``f(t)``) и не чинит выдуманные
OCR пробелы внутри слова («Гурви ца»). Там нет однозначного правила, а цена
ошибки — испорченный корректный текст.
"""

from __future__ import annotations

import re
from collections import Counter

# Латиница -> кириллица. Два класса замен:
#   1. настоящие гомоглифы (глифы неотличимы): a/а, c/с, e/е, o/о, p/р, x/х, y/у
#      и их заглавные — их OCR путает в любом языке;
#   2. устойчивые ошибки формы, характерные для кириллицы: n->п, r->г.
# Буквы, которые в замерах давали неоднозначный результат (w — то «ш», то «ы»;
# t/s/i/l/I/J — почти всегда обломки формул), в карту намеренно не входят.
_LAT_TO_CYR = {
    "a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у",
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К",
    "M": "М", "O": "О", "P": "Р", "T": "Т", "X": "Х",
    "n": "п", "r": "г",
}

# Слова, где общая карта угадывает неверно. `n` в этом корпусе — почти всегда
# «п» (~400 случаев), но в «дnя» это «л». Список открытый: сюда попадает только
# то, что реально встретилось и было проверено глазами.
_WORD_OVERRIDES = {
    "дnя": "для",
    "Дnя": "Для",
}

_CYRILLIC = re.compile(r"[а-яА-ЯёЁ]")
_LATIN = re.compile(r"[a-zA-Z]")
_WORD = re.compile(r"[а-яА-ЯёЁa-zA-Z]+")


def _repair_word(word: str) -> str:
    """Чинит одно слово, если оно уверенно опознано как русское с латиницей внутри."""
    override = _WORD_OVERRIDES.get(word)
    if override is not None:
        return override

    latin = _LATIN.findall(word)
    if not latin:
        return word

    cyrillic = _CYRILLIC.findall(word)
    # Три условия, каждое отсекает свой класс ложных срабатываний:
    #   - >=2 кириллических: одиночная буква рядом с латиницей — это формула;
    #   - латиницы не больше кириллицы: слово должно быть русским по сути,
    #     иначе мы покалечим `sin`, `cos`, `exp`, имена переменных;
    #   - каждая латинская буква есть в карте: незнакомая означает, что перед
    #     нами не подмена гомоглифа, а что-то другое — не трогаем вовсе.
    if len(cyrillic) < 2 or len(latin) > len(cyrillic):
        return word
    if any(ch not in _LAT_TO_CYR for ch in latin):
        return word

    return "".join(_LAT_TO_CYR.get(ch, ch) for ch in word)


def repair_homoglyphs(text: str) -> str:
    """Возвращает текст, где латиница внутри русских слов заменена на кириллицу."""
    if not text:
        return ""
    return _WORD.sub(lambda m: _repair_word(m.group(0)), text)


def join_hyphenated_linebreaks(text: str) -> str:
    """Сшивает слово, разорванное переносом на границе строк.

    Мягкий перенос (U+00AD) снимаем всегда — в тексте он не значит ничего, кроме
    «здесь была граница строки». Обычный дефис убираем, только когда за ним идёт
    перевод строки: дефис внутри строки может быть настоящим («Рауса-Гурвица»).
    """
    if not text:
        return ""
    text = re.sub(r"­[ \t]*\r?\n[ \t]*", "", text)
    text = re.sub(r"­", "", text)
    text = re.sub(r"(\w)-[ \t]*\r?\n[ \t]*(\w)", r"\1\2", text)
    return text


def repair_scanned_text(text: str) -> str:
    """Полный ремонт текстового слоя скана: переносы + гомоглифы.

    Порядок важен: сначала сшиваем перенесённые слова, иначе «веществен» и
    «ными» разбираются как два отдельных слова и правило «>=2 кириллических
    букв» отработает не на том фрагменте.
    """
    if not text:
        return ""
    return repair_homoglyphs(join_hyphenated_linebreaks(text))

# --- Колонтитулы -----------------------------------------------------------
#
# Выгрузки правовых баз и печатных PDF несут на каждой странице шапку и
# подвал: имя базы, «Страница N из M», дата сохранения, повтор названия
# документа. В извлечённом тексте они врезаются в середину предложения:
#
#     «Воздуховоды ... должны быть выполнены с КонсультантПлюс надежная
#      правовая поддержка www.consultant.ru Страница 129 из 133 ...
#      одинаково большим пределом огнестойкости.»
#
# Замер 04.09.2026 на СП 60.13330.2020: 270 таких вставок, около 8% объёма
# файла. Они не только рвут фразы, но и выигрывают места в поисковой выдаче:
# на вопрос про скорость воды первым фрагментом пришёл кусок, состоящий из
# колонтитула целиком.
#
# Порог намеренно НЕ «повторяется N раз». Замер на том же файле: настоящий
# текст повторяется до 18 раз («температуре теплоносителя не более 95 °C» -
# 18 вхождений, строки таблиц - 16), а колонтитул - 130-134. Любой порог
# около десятка выкосил бы содержание. Поэтому считаем не повторы, а долю
# страниц: строка, которая есть минимум на половине страниц, - это оформление
# страницы, а не текст.

# Средняя высота страницы в строках. Нужна только чтобы оценить число страниц
# по объёму текста: на СП 60 - 5797 строк на 134 страницы, то есть 43.
_LINES_PER_PAGE = 45
_FURNITURE_MIN_PAGE_SHARE = 0.5
# Абсолютный минимум: на коротком документе доля страниц ничего не значит.
_FURNITURE_MIN_REPEATS = 8
_FURNITURE_MAX_LEN = 200
# Строка обязана быть текстом, а не разметкой. Отсекает «----», «# <1>», «НН»
# и голые числовые строки таблиц, которые тоже повторяются часто.
_FURNITURE_MIN_LETTERS = 8

# Сколько групп цифр разрешено замаскировать. Маскировка нужна ровно для
# номера страницы и даты («Страница 12 из 133» и «Страница 13 из 133» - один
# колонтитул), и на этом её работа кончается. Без потолка она схлопывает
# однотипные СТРОКИ ТАБЛИЦ: «от 300 до 1000 включ. - 0,7» и «от 1000 до 2000
# включ. - 0,9» дают один ключ, и на длинном справочнике такой ключ наберёт
# частоту колонтитула. Настоящие колонтитулы укладываются в три группы
# (страница из страниц, дата), строки таблиц - нет.
_FURNITURE_MAX_DIGIT_GROUPS = 3
# Предохранитель: если правило собралось выкинуть столько, документ явно не
# такой, как мы думаем, - лучше не трогать ничего.
_FURNITURE_MAX_REMOVED_SHARE = 0.2

_DIGITS_RE = re.compile(r"\d+")


def _furniture_key(line):
    """Строка с замаскированными числами: «Страница 12 из 133» и «Страница 13
    из 133» - один и тот же колонтитул."""
    return _DIGITS_RE.sub("#", " ".join(line.split()).casefold())


def strip_page_furniture(text):
    """Убирает шапки и подвалы страниц из извлечённого текста.

    Возвращает текст без изменений, если ничего уверенно не опознано.
    """
    if not text:
        return text

    lines = text.split(chr(10))
    pages = max(1, len(lines) / _LINES_PER_PAGE)
    threshold = max(_FURNITURE_MIN_REPEATS, int(pages * _FURNITURE_MIN_PAGE_SHARE))

    counts = Counter(_furniture_key(l) for l in lines if l.strip())
    furniture = {
        key
        for key, n in counts.items()
        if n >= threshold
        and len(key) <= _FURNITURE_MAX_LEN
        and sum(ch.isalpha() for ch in key) >= _FURNITURE_MIN_LETTERS
        and key.count("#") <= _FURNITURE_MAX_DIGIT_GROUPS
    }
    if not furniture:
        return text

    kept = [l for l in lines if not (l.strip() and _furniture_key(l) in furniture)]
    if len(lines) - len(kept) > len(lines) * _FURNITURE_MAX_REMOVED_SHARE:
        return text
    return chr(10).join(kept)


def strip_pdf_page_furniture(pages):
    """Оцениваем повторяемость по всему PDF, сохраняя номера страниц.

    Одна плотная страница (оглавление или история поправок) не даёт
    достаточного основания удалить повторяющиеся строки как колонтитулы.
    """
    combined = "\n".join(text for _number, text in pages)
    retained_lines = set(strip_page_furniture(combined).split("\n"))
    return [
        (number, "\n".join(line for line in text.split("\n") if line in retained_lines))
        for number, text in pages
    ]
